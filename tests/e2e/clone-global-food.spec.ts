import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";

test("signed-in user reviews a global food and saves an independent personal copy", async ({ page }) => {
  const copyName = `A copy ${randomUUID()}`;
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/food?q=Test%20food%2001");
  await expect(page.getByRole("link", { name: /Copy .* to My foods/ })).toHaveCount(0);
  await page.goto("/food/personal/new?clone=e2e-01");
  await expect(page).toHaveURL(/\/food$/);
  await expect(page.getByRole("heading", { name: "Copy global food" })).toHaveCount(0);
  await page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign in with Google" }).click();
  await page.getByRole("link", { name: "Continue as Test User" }).click();
  await page.goto("/food?view=global&q=Test%20food%2001");
  const source = page.getByRole("list", { name: "Full food catalog" }).getByRole("listitem").filter({ hasText: "Test food 01" });
  await expect(source).toContainText("100 kcal");
  const copy = source.getByRole("link", { name: "Copy Test food 01 to My foods" });
  await copy.focus();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/\/food\/personal\/new\?clone=e2e-01$/);
  await expect(page.getByRole("heading", { name: "Copy global food" })).toBeVisible();
  await expect(page.locator('input[name="name"]')).toHaveValue("Test food 01");
  await expect(page.locator('select[name="unit"]')).toHaveValue("g");
  await expect(page.locator('input[name="referenceAmount"]')).toHaveValue("100");
  await expect(page.locator('input[name="calories"]')).toHaveValue("100");
  await expect(page.locator('input[name="protein"]')).toHaveValue("1");
  await page.locator('input[name="name"]').fill(copyName);
  await page.getByRole("button", { name: "Create copy" }).click();
  await expect(page).toHaveURL(/\/food#personal-foods$/);
  const item = page.getByRole("list", { name: "My foods" }).getByRole("listitem").filter({ hasText: copyName });
  await expect(item).toContainText("100 kcal");
  const editHref = await item.getByRole("link", { name: `Edit ${copyName}` }).getAttribute("href");
  expect(editHref).toContain("personal-");
  await page.goto(editHref!);
  await page.locator('input[name="calories"]').fill("123");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(item).toContainText("123 kcal");
  await page.goto("/food?view=global&q=Test%20food%2001");
  await expect(source).toContainText("100 kcal");
  await expect(source).not.toContainText("123 kcal");
  await expect(page.getByRole("link", { name: "Copy Test food 01 to My foods" })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/food$/);
  await expect(page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign in with Google" })).toBeVisible();
  await page.goto("/food?q=Test%20food%2001");
  await expect(page.getByRole("link", { name: /Copy .* to My foods/ })).toHaveCount(0);
  expect(await (await page.request.get("/food?q=Test%20food%2001")).text()).not.toContain(copyName);
});

test("missing calories require correction and invalid sources cannot start a copy", async ({ page }) => {
  const copyName = `A missing ${randomUUID()}`;
  await page.goto("/food");
  await page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign in with Google" }).click();
  await page.getByRole("link", { name: "Continue as Test User" }).click();
  await page.goto("/food/personal/new?clone=absent-global-food");
  await expect(page.getByText("This page could not be found")).toBeVisible();
  await page.goto("/food/personal/new?clone=e2e-missing-calories");
  await page.locator('input[name="name"]').fill(copyName);
  await page.getByRole("link", { name: "Cancel" }).click();
  await expect(page).toHaveURL(/\/food\?view=global$/);
  await page.getByRole("link", { name: "My foods", exact: true }).click();
  await expect(page.getByRole("list", { name: "My foods" }).getByText(copyName)).toHaveCount(0);
  await page.goto("/food/personal/new?clone=e2e-missing-calories");
  await expect(page.getByText("The global food has no calories. Enter calories before saving your copy.")).toBeVisible();
  await expect(page.locator('input[name="calories"]')).toHaveValue("");
  await expect(page.locator('input[name="protein"]')).toHaveValue("");
  await expect(page.locator('input[name="carbohydrates"]')).toHaveValue("0");
  await expect(page.locator('input[name="fat"]')).toHaveValue("0");
  await page.locator('input[name="name"]').fill(copyName);
  await page.getByRole("button", { name: "Create copy" }).click();
  await expect(page.getByText("Enter a number of zero or more.")).toBeVisible();
  await expect(page.locator('input[name="name"]')).toHaveValue(copyName);
  await page.locator('input[name="calories"]').fill("42");
  await page.getByRole("button", { name: "Create copy" }).click();
  await expect(page).toHaveURL(/\/food#personal-foods$/);
  const item = page.getByRole("list", { name: "My foods" }).getByRole("listitem").filter({ hasText: copyName });
  await expect(item).toContainText("42 kcal");
  await expect(item).toContainText("Unavailable");
});
