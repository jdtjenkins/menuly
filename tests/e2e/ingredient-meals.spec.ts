  await page.goto(`${mealUrl}/edit`);
  await page.getByRole("form", { name: "Edit meal" }).locator('input[name="name"]').fill(`${mealName} edited`);
  await page.getByRole("spinbutton", { name: "Amount for Test food 01" }).fill("100");
