  expect(await list.evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(" ").length)).toBe(3);
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await list.evaluate((element) => getComputedStyle(element).gridTemplateColumns.split(" ").length)).toBe(1);
  const card = list.getByRole("link").filter({ hasText: mealName });
  await card.focus();
  await expect(card).toBeFocused();
