  await expect(page.getByText("50 g Test food 01")).toBeVisible();
  await expect(page.getByText(`100 ml ${privateName}`)).toBeVisible();
  await expect(page.getByText(`Missing protein for ${privateName}.`).first()).toBeVisible();
  await expect(page.getByText("At least 0.5 g", { exact: false }).first()).toBeVisible();
  await expect(page.getByText("0.5 g", { exact: true }).first()).toBeVisible();
  await expect(page.getByRole("heading", { name: "Selected servings" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Whole recipe" })).toHaveCount(0);
  await expect(page.getByRole("spinbutton", { name: "Selected servings" })).toHaveValue("4");
  await expect(page.getByText("50 kcal")).toBeVisible();
  await expect(page.getByRole("button", { name: "Reset servings" })).toHaveCount(0);
  await page.getByRole("spinbutton", { name: "Selected servings" }).fill("1.5");
  await expect(page.getByText("18.75 kcal")).toBeVisible();
  await expect(page.getByRole("button", { name: "Reset servings" })).toBeVisible();
  await page.getByRole("button", { name: "Reset servings" }).click();
  await expect(page.getByRole("spinbutton", { name: "Selected servings" })).toHaveValue("4");
