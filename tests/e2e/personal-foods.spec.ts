import { randomUUID } from "node:crypto";
import { expect, test } from "@playwright/test";
import { encode } from "next-auth/jwt";

test("personal foods can be created and edited, then disappear after sign-out", async ({ page }) => {
  const name = `Private ${randomUUID()}`;
  await page.setViewportSize({ width: 375, height: 812 });
  await page.goto("/food");
  await expect(page.getByRole("heading", { name: "My foods" })).toHaveCount(0);
  await page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign in with Google" }).click();
  await page.getByRole("link", { name: "Continue as Test User" }).click();
  await expect(page.getByRole("heading", { name: "My foods" })).toBeVisible();
  await page.getByRole("link", { name: "Create personal food" }).click();
  await expect(page).toHaveURL(/\/food\/personal\/new$/);
  await page.getByRole("button", { name: "Create food" }).click();
  await expect(page.getByText("Enter a name up to 100 characters.")).toBeVisible();
  await page.locator('input[name="name"]').fill(name);
  await page.getByRole("button", { name: "Create food" }).click();
  await expect(page.locator('input[name="name"]')).toHaveValue(name);
  await expect(page.getByText("Enter a positive amount.")).toBeVisible();
  await page.locator('select[name="unit"]').selectOption("g");
  await page.locator('input[name="referenceAmount"]').fill("100");
  await page.locator('input[name="calories"]').fill("0");
  await page.locator('input[name="carbohydrates"]').fill("0");
  await page.locator('select[name="unit"]').selectOption("g");
  await expect(page.locator('select[name="unit"]')).toHaveValue("g");
  await page.getByRole("button", { name: "Create food" }).click();
  await expect(page).toHaveURL(/\/food#personal-foods$/);
  const item = page.getByRole("list", { name: "My foods" }).getByRole("listitem").filter({ hasText: name });
  await expect(item).toContainText("0 kcal");
  await expect(item).toContainText("Unavailable");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const edit = item.getByRole("link", { name: `Edit ${name}` });
  const editHref = await edit.getAttribute("href");
  expect(editHref).toContain("personal-");
  await edit.focus();
  await page.keyboard.press("Enter");
  await expect(page).toHaveURL(/\/edit$/);
  await expect(page.getByText("g (fixed)")).toBeVisible();
  const editForm = page.getByRole("form", { name: "Edit personal food" });
  await expect(editForm.getByRole("combobox")).toHaveCount(0);
  await editForm.locator('input[name="protein"]').fill("5");
  await editForm.locator('input[name="carbohydrates"]').fill("");
  await page.getByRole("button", { name: "Save changes" }).click();
  await expect(page).toHaveURL(/\/food#personal-foods$/);
  await expect(item).toContainText("5 g");
  await expect(item).toContainText("Unavailable");
  await page.goto(editHref!);
  await expect(page.getByRole("form", { name: "Edit personal food" }).locator('input[name="protein"]')).toHaveValue("5");
  await expect(page.getByRole("form", { name: "Edit personal food" }).locator('input[name="carbohydrates"]')).toHaveValue("");
  await page.goto("/food");
  const archive = item.getByRole("button", { name: `Archive ${name}` });
  await archive.focus();
  await page.keyboard.press("Enter");
  await expect(item.getByText(`Archive ${name}? It will be removed from My foods.`)).toBeVisible();
  await item.getByRole("button", { name: "Cancel" }).click();
  await expect(item).toBeVisible();
  await archive.click();
  await item.getByRole("button", { name: "Confirm archive" }).click();
  await expect(page).toHaveURL(/\/food#personal-foods$/);
  await expect(item).toHaveCount(0);
  await page.goto(editHref!);
  await expect(page.getByText("This page could not be found")).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  const otherSession = await encode({ token: { userId: "playwright-other-account" }, secret: "playwright-only-session-secret-with-sufficient-length", salt: "authjs.session-token", maxAge: 3600 });
  await page.context().addCookies([{ name: "authjs.session-token", value: otherSession, url: "http://localhost:3100" }]);
  await page.goto(editHref!);
  await expect(page.getByRole("heading", { name: "Edit personal food" })).toHaveCount(0);
  await expect(page.getByText("This page could not be found")).toBeVisible();
  await page.goto("/food/personal/e2e-01/edit");
  await expect(page.getByText("This page could not be found")).toBeVisible();
  await page.goto("/food/personal/absent/edit");
  await expect(page.getByText("This page could not be found")).toBeVisible();
  await page.goto("/food");
  await expect(page.getByRole("heading", { name: "My foods" })).toBeVisible();
  await expect(page.getByText("No personal foods yet. Create one to get started.")).toBeVisible();
  await expect(page.getByRole("list", { name: "My foods" }).getByText(name)).toHaveCount(0);
  await page.getByRole("navigation", { name: "Primary navigation" }).getByRole("button", { name: "Sign out" }).click();
  await expect(page).toHaveURL(/\/food$/);
  await expect(page.getByRole("heading", { name: "My foods" })).toHaveCount(0);
  expect(await (await page.request.get("/food")).text()).not.toContain(name);
  await page.goto(editHref!);
  await expect(page).toHaveURL(/\/food$/);
});
